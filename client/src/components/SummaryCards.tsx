import { useState } from "react";
import type { DashboardSummary } from "../types";
import { compactNumber, formatComparisonText, fullNumber, usd } from "../format";
import { InfoTip } from "./InfoTip";

function costPerMillionTokens(costUsd: number, totalTokens: number): number | null {
  if (totalTokens <= 0) return null;
  return (costUsd / totalTokens) * 1_000_000;
}

interface Props {
  summary: DashboardSummary;
  rangeSubLabel: string;
  totalCostForecast?: {
    value: number;
    label: string;
    comparison?: string;
    comparisonTone?: "positive" | "negative" | "neutral";
    sub?: string;
    info?: string;
  } | null;
}

interface Card {
  label: string;
  value: string;
  sub?: string;
  comparison?: string;
  comparisonTone?: "positive" | "negative" | "neutral";
  accent: string;
  info: string;
}

export function SummaryCards({ summary, rangeSubLabel, totalCostForecast = null }: Props) {
  const [showForecastBack, setShowForecastBack] = useState(false);
  const costPerMillion = costPerMillionTokens(summary.totalCostUsd, summary.totalTokens);
  const previousCost = summary.comparisons?.totalCostUsd?.previousValue;
  const previousTokens = summary.comparisons?.totalTokens?.previousValue;
  const previousCostPerMillion =
    previousCost != null && previousTokens != null ? costPerMillionTokens(previousCost, previousTokens) : null;
  const costPerMillionComparison =
    costPerMillion != null && previousCostPerMillion != null
      ? {
          previousValue: previousCostPerMillion,
          deltaValue: costPerMillion - previousCostPerMillion,
          deltaPercent:
            previousCostPerMillion === 0
              ? costPerMillion === 0
                ? 0
                : 100
              : ((costPerMillion - previousCostPerMillion) / previousCostPerMillion) * 100,
          direction:
            costPerMillion > previousCostPerMillion
              ? ("up" as const)
              : costPerMillion < previousCostPerMillion
                ? ("down" as const)
                : ("same" as const),
          label: summary.comparisons?.totalCostUsd?.label ?? "the previous period",
        }
      : undefined;
  const cards: Card[] = [
    {
      label: "Total Cost",
      value: usd(summary.totalCostUsd),
      sub: rangeSubLabel,
      comparison: formatComparisonText(summary.comparisons?.totalCostUsd, "currency", rangeSubLabel),
      comparisonTone:
        summary.comparisons?.totalCostUsd?.direction === "up"
          ? "positive"
          : summary.comparisons?.totalCostUsd?.direction === "down"
            ? "negative"
            : "neutral",
      accent: "var(--accent-cost)",
      info: "Total estimated USD spend across all models and products in the selected range, after any plan discounts.",
    },
    {
      label: "Total Tokens",
      value: compactNumber(summary.totalTokens),
      sub: fullNumber(summary.totalTokens),
      comparison: formatComparisonText(summary.comparisons?.totalTokens, "number", rangeSubLabel),
      comparisonTone:
        summary.comparisons?.totalTokens?.direction === "up"
          ? "positive"
          : summary.comparisons?.totalTokens?.direction === "down"
            ? "negative"
            : "neutral",
      accent: "var(--accent-1)",
      info: "All tokens processed: uncached input + cache reads + cache creation + output.",
    },
    {
      label: "Output Tokens",
      value: compactNumber(summary.outputTokens),
      sub: fullNumber(summary.outputTokens),
      comparison: formatComparisonText(summary.comparisons?.outputTokens, "number", rangeSubLabel),
      comparisonTone:
        summary.comparisons?.outputTokens?.direction === "up"
          ? "positive"
          : summary.comparisons?.outputTokens?.direction === "down"
            ? "negative"
            : "neutral",
      accent: "var(--accent-2)",
      info: "Tokens generated by the model. Billed at the higher output rate than input.",
    },
    {
      label: "Cache Hit Rate",
      value: `${summary.cacheHitRate.toFixed(1)}%`,
      sub: `${compactNumber(summary.cacheReadTokens)} cached reads`,
      comparison: formatComparisonText(summary.comparisons?.cacheHitRate, "percent", rangeSubLabel),
      comparisonTone:
        summary.comparisons?.cacheHitRate?.direction === "up"
          ? "positive"
          : summary.comparisons?.cacheHitRate?.direction === "down"
            ? "negative"
            : "neutral",
      accent: "var(--accent-3)",
      info: "Share of input served from the prompt cache: cache reads ÷ (cache reads + uncached input). Higher means more reuse and lower cost.",
    },
    {
      label: "Cost / 1M Tokens",
      value: costPerMillion != null ? usd(costPerMillion) : "—",
      sub: `${fullNumber(summary.totalTokens)} total tokens`,
      comparison: formatComparisonText(costPerMillionComparison, "currency", rangeSubLabel),
      comparisonTone:
        costPerMillionComparison?.direction === "up"
          ? "negative"
          : costPerMillionComparison?.direction === "down"
            ? "positive"
            : "neutral",
      accent: "var(--accent-4)",
      info: "Average spend per 1M total tokens across the selected range. Lower is more efficient; trend compares this blended rate with the previous period.",
    },
  ];

  return (
    <div className="cards">
      {cards.map((c) => {
        if (c.label === "Total Cost" && totalCostForecast) {
          return (
            <div className={showForecastBack ? "card card-flip-wrap card-forecast-visible" : "card card-flip-wrap"} key={c.label}>
              <div className={showForecastBack ? "card-flip-inner card-flipped" : "card-flip-inner"}>
                <div className="card-face card-face-front">
                  <button
                    type="button"
                    className="card-flip-btn"
                    aria-label="Show predicted month-end total cost"
                    title="Show predicted month-end total cost"
                    onClick={() => setShowForecastBack(true)}
                  >
                    <svg className="card-flip-icon" viewBox="0 0 24 24" aria-hidden="true">
                      <path
                        d="M5 16.5L10.2 11.3L13.7 14.8L19 9.5"
                        fill="none"
                        stroke="currentColor"
                        strokeWidth="1.9"
                        strokeLinecap="round"
                        strokeLinejoin="round"
                      />
                      <path
                        d="M14.5 9.5H19V14"
                        fill="none"
                        stroke="currentColor"
                        strokeWidth="1.9"
                        strokeLinecap="round"
                        strokeLinejoin="round"
                      />
                    </svg>
                  </button>
                  <div className="card-label">
                    <span className="card-label-text">{c.label}</span>
                    <InfoTip text={c.info} />
                  </div>
                  <div className="card-value">{c.value}</div>
                  {c.comparison && <div className={`card-comparison ${c.comparisonTone ?? "neutral"}`}>{c.comparison}</div>}
                </div>
                <div className="card-face card-face-back">
                  <button
                    type="button"
                    className="card-flip-btn"
                    aria-label="Show current total cost"
                    title="Show current total cost"
                    onClick={() => setShowForecastBack(false)}
                  >
                    <svg className="card-flip-icon card-flip-icon-close" viewBox="0 0 24 24" aria-hidden="true">
                      <path
                        d="M8 8L16 16"
                        fill="none"
                        stroke="currentColor"
                        strokeWidth="1.9"
                        strokeLinecap="round"
                      />
                      <path
                        d="M16 8L8 16"
                        fill="none"
                        stroke="currentColor"
                        strokeWidth="1.9"
                        strokeLinecap="round"
                      />
                    </svg>
                  </button>
                  <div className="card-label">
                    <span className="card-label-text">{totalCostForecast.label}</span>
                    <InfoTip text={totalCostForecast.info ?? "Projected month-end total cost using trailing 30-day weekday-aware daily cost averages for the remaining days of the current month."} />
                  </div>
                  <div className="card-value">{usd(totalCostForecast.value)}</div>
                  {totalCostForecast.comparison && (
                    <div className={`card-comparison ${totalCostForecast.comparisonTone ?? "neutral"}`}>{totalCostForecast.comparison}</div>
                  )}
                </div>
              </div>
            </div>
          );
        }

        return (
          <div className="card" key={c.label}>
            <div className="card-label">
              <span className="card-label-text">{c.label}</span>
              <InfoTip text={c.info} />
            </div>
            <div className="card-value">{c.value}</div>
            {c.comparison && <div className={`card-comparison ${c.comparisonTone ?? "neutral"}`}>{c.comparison}</div>}
          </div>
        );
      })}
    </div>
  );
}
